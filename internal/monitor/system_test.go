func TestParseDNSServers(t *testing.T) {
	cases := []struct {
		name     string
		content  string
		expected string
	}{
		{
			name:     "empty",
			content:  "",
			expected: "System defaults",
		},
		{
			name:     "comments only",
			content:  "# generated by NetworkManager\n# nameserver 10.0.0.1",
			expected: "System defaults",
		},
		{
			name:     "single server",
			content:  "nameserver 8.8.8.8\n",
			expected: "8.8.8.8",
		},
		{
			name:     "multiple servers clamped to three",
			content:  "nameserver 1.1.1.1\nnameserver 8.8.8.8\nnameserver 9.9.9.9\nnameserver 8.8.4.4\n",
			expected: "1.1.1.1, 8.8.8.8, 9.9.9.9",
		},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := parseDNSServers(c.content)
			if got != c.expected {
				t.Errorf("parseDNSServers() = %q; want %q", got, c.expected)
			}
		})
	}
}

func TestGetDisksInfo(t *testing.T) {
	disks := GetDisksInfo()
	// Should not panic, and returns a list on typical machines
	for _, d := range disks {
		if d.Mountpoint == "" {
			t.Errorf("unexpected empty mountpoint")
		}
		if d.TotalGB < 0 {
			t.Errorf("unexpected negative total size: %f", d.TotalGB)
		}
	}
}
