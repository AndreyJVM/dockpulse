func TestGetSystemInfo(t *testing.T) {
	info := GetSystemInfo()
	if info.Hostname == "" {
		t.Errorf("expected non-empty hostname")
	}
	if info.OS == "" {
		t.Errorf("expected non-empty OS")
	}
}

